do $$ begin create role anon nologin; exception when duplicate_object then null; end $$;
do $$ begin create role authenticated nologin; exception when duplicate_object then null; end $$;
do $$ begin create role service_role nologin bypassrls; exception when duplicate_object then null; end $$;
create schema auth;
create table auth.users (id uuid primary key);
create function auth.uid() returns uuid language sql stable as $$
  select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
$$;
create function auth.role() returns text language sql stable as $$
  select nullif(current_setting('request.jwt.claim.role', true), '')
$$;

create table public.profiles (id uuid primary key references auth.users(id), role text not null);
create function public.is_staff() returns boolean language sql stable security definer set search_path = public as $$
  select coalesce((select role in ('editor','admin','super_admin') from profiles where id = auth.uid()), false)
$$;
grant execute on function public.is_staff() to anon, authenticated;

