-- Confirmed production contract: the two count columns are positions 16/17,
-- in this order, and both are bigint. The repair must append metadata without
-- renaming, reordering, or changing either count type.
create view public.zemaris_with_counts
with (security_invoker = true)
as
select
  z.id, z.slug, z.name, z.name_amharic, z.bio, z.bio_amharic,
  z.image_path, z.image_alt, z.youtube_url, z.website_url,
  z.sort_order, z.is_featured, z.status, z.created_at, z.updated_at,
  (select count(*) from public.mezmur_data_import m where m.zemari_id = z.id) as mezmur_count,
  (select count(*) from public.mezmur_data_import m
    where m.zemari_id = z.id and lower(trim(coalesce(m.status, ''))) = 'published') as published_mezmur_count
from public.zemaris z;

