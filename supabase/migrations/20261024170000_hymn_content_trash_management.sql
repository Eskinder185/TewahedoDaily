-- Secure trash, restore, and permanent deletion for the active Hymns CMS tables.
-- Forward-only. No content is moved or deleted when this migration is applied.

begin;

alter table public.mezmur_data_import
  add column if not exists deleted_at timestamptz,
  add column if not exists deleted_by uuid references auth.users(id) on delete set null,
  add column if not exists deleted_from_status text;

alter table public.zemaris
  add column if not exists deleted_at timestamptz,
  add column if not exists deleted_by uuid references auth.users(id) on delete set null,
  add column if not exists deleted_from_status text;

alter table public.mezmur_collections_import
  add column if not exists deleted_at timestamptz,
  add column if not exists deleted_by uuid references auth.users(id) on delete set null,
  add column if not exists deleted_from_status text;

alter table public.mezmur_sections_import
  add column if not exists deleted_at timestamptz,
  add column if not exists deleted_by uuid references auth.users(id) on delete set null,
  add column if not exists deleted_from_status text;

create index if not exists mezmur_data_import_deleted_at_idx
  on public.mezmur_data_import (deleted_at) where deleted_at is not null;
create index if not exists zemaris_deleted_at_idx
  on public.zemaris (deleted_at) where deleted_at is not null;

create table if not exists public.content_deletion_events (
  id bigint generated by default as identity primary key,
  content_type text not null check (content_type in ('mezmur', 'zemari', 'collection', 'section')),
  content_key text not null,
  content_title text,
  action text not null check (action in ('trashed', 'restored', 'permanently_deleted', 'reassigned_and_deleted')),
  actor_id uuid references auth.users(id) on delete set null,
  actor_role text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.content_deletion_events enable row level security;
revoke all on public.content_deletion_events from public, anon, authenticated;
grant select on public.content_deletion_events to authenticated;
drop policy if exists content_deletion_events_staff_read on public.content_deletion_events;
create policy content_deletion_events_staff_read
  on public.content_deletion_events for select to authenticated
  using (coalesce(public.is_staff(), false));

create or replace function public.trash_hymn_content(p_content_type text, p_content_key text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := auth.uid();
  v_role text;
  v_key text := trim(coalesce(p_content_key, ''));
  v_title text;
  v_previous text;
  v_changed integer := 0;
begin
  select role::text into v_role from public.profiles where id = v_actor;
  if v_actor is null or v_role not in ('admin', 'super_admin') then
    raise exception 'An admin or super admin role is required to move content to Trash' using errcode = '42501';
  end if;
  if v_key = '' then raise exception 'Content key is required' using errcode = '22023'; end if;

  if p_content_type = 'mezmur' then
    select title, status into v_title, v_previous
    from public.mezmur_data_import
    where mezmur_id = v_key or slug = v_key
    order by case when mezmur_id = v_key then 0 else 1 end limit 1 for update;
    if not found then raise exception 'Mezmur not found' using errcode = 'P0002'; end if;
    update public.mezmur_data_import
      set deleted_at = coalesce(deleted_at, now()), deleted_by = coalesce(deleted_by, v_actor),
          deleted_from_status = coalesce(deleted_from_status, status), status = 'draft',
          updated_at = clock_timestamp()::text
      where (mezmur_id = v_key or slug = v_key) and deleted_at is null;
    get diagnostics v_changed = row_count;
  elsif p_content_type = 'zemari' then
    select name, status into v_title, v_previous from public.zemaris where id::text = v_key or slug = v_key limit 1 for update;
    if not found then raise exception 'Zemari not found' using errcode = 'P0002'; end if;
    update public.zemaris
      set deleted_at = coalesce(deleted_at, now()), deleted_by = coalesce(deleted_by, v_actor),
          deleted_from_status = coalesce(deleted_from_status, status), status = 'archived'
      where (id::text = v_key or slug = v_key) and deleted_at is null;
    get diagnostics v_changed = row_count;
  elsif p_content_type = 'collection' then
    select title, status into v_title, v_previous from public.mezmur_collections_import
      where collection_id = v_key or collection_slug = v_key limit 1 for update;
    if not found then raise exception 'Mezmur collection not found' using errcode = 'P0002'; end if;
    update public.mezmur_collections_import
      set deleted_at = coalesce(deleted_at, now()), deleted_by = coalesce(deleted_by, v_actor),
          deleted_from_status = coalesce(deleted_from_status, status), status = 'archived'
      where (collection_id = v_key or collection_slug = v_key) and deleted_at is null;
    get diagnostics v_changed = row_count;
  elsif p_content_type = 'section' then
    select title, status into v_title, v_previous from public.mezmur_sections_import
      where section_id = v_key or section_slug = v_key limit 1 for update;
    if not found then raise exception 'Mezmur section not found' using errcode = 'P0002'; end if;
    update public.mezmur_sections_import
      set deleted_at = coalesce(deleted_at, now()), deleted_by = coalesce(deleted_by, v_actor),
          deleted_from_status = coalesce(deleted_from_status, status), status = 'archived'
      where (section_id = v_key or section_slug = v_key) and deleted_at is null;
    get diagnostics v_changed = row_count;
  else
    raise exception 'Unsupported Hymns content type: %', p_content_type using errcode = '22023';
  end if;

  if v_changed > 0 then
    insert into public.content_deletion_events(content_type, content_key, content_title, action, actor_id, actor_role, details)
    values (p_content_type, v_key, v_title, 'trashed', v_actor, v_role, jsonb_build_object('previous_status', v_previous));
  end if;
  return jsonb_build_object('content_type', p_content_type, 'content_key', v_key, 'action', 'trashed', 'changed', v_changed > 0);
end;
$$;

create or replace function public.restore_hymn_content(p_content_type text, p_content_key text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := auth.uid();
  v_role text;
  v_key text := trim(coalesce(p_content_key, ''));
  v_title text;
  v_changed integer := 0;
begin
  select role::text into v_role from public.profiles where id = v_actor;
  if v_actor is null or v_role not in ('admin', 'super_admin') then
    raise exception 'An admin or super admin role is required to restore content' using errcode = '42501';
  end if;

  if p_content_type = 'mezmur' then
    update public.mezmur_data_import set deleted_at = null, deleted_by = null, deleted_from_status = null,
      status = 'draft', updated_at = clock_timestamp()::text
      where (mezmur_id = v_key or slug = v_key) and deleted_at is not null returning title into v_title;
  elsif p_content_type = 'zemari' then
    update public.zemaris set deleted_at = null, deleted_by = null, deleted_from_status = null, status = 'draft'
      where (id::text = v_key or slug = v_key) and deleted_at is not null returning name into v_title;
  elsif p_content_type = 'collection' then
    update public.mezmur_collections_import set deleted_at = null, deleted_by = null, deleted_from_status = null, status = 'draft'
      where (collection_id = v_key or collection_slug = v_key) and deleted_at is not null returning title into v_title;
  elsif p_content_type = 'section' then
    update public.mezmur_sections_import set deleted_at = null, deleted_by = null, deleted_from_status = null, status = 'draft'
      where (section_id = v_key or section_slug = v_key) and deleted_at is not null returning title into v_title;
  else
    raise exception 'Unsupported Hymns content type: %', p_content_type using errcode = '22023';
  end if;
  get diagnostics v_changed = row_count;
  if v_changed = 0 then raise exception 'Trashed content was not found' using errcode = 'P0002'; end if;

  insert into public.content_deletion_events(content_type, content_key, content_title, action, actor_id, actor_role)
  values (p_content_type, v_key, v_title, 'restored', v_actor, v_role);
  return jsonb_build_object('content_type', p_content_type, 'content_key', v_key, 'action', 'restored', 'status', 'draft');
end;
$$;

create or replace function public.permanently_delete_hymn_content(p_content_type text, p_content_key text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := auth.uid();
  v_role text;
  v_key text := trim(coalesce(p_content_key, ''));
  v_slug text;
  v_title text;
  v_related integer := 0;
begin
  select role::text into v_role from public.profiles where id = v_actor;
  if v_actor is null or v_role is distinct from 'super_admin' then
    raise exception 'Only a super admin can permanently delete content' using errcode = '42501';
  end if;

  if p_content_type = 'mezmur' then
    select slug, title into v_slug, v_title from public.mezmur_data_import
      where (mezmur_id = v_key or slug = v_key) and deleted_at is not null limit 1 for update;
    if not found then raise exception 'Move this Mezmur to Trash before permanently deleting it' using errcode = '23514'; end if;
    delete from public.mezmur_section_links_import where mezmur_slug = v_slug;
    delete from public.mezmur_category_links_import where mezmur_slug = v_slug;
    delete from public.mezmur_occasion_links_import where mezmur_slug = v_slug;
    delete from public.mezmur_data_import where (mezmur_id = v_key or slug = v_key) and deleted_at is not null;
  elsif p_content_type = 'zemari' then
    select id::text, name into v_slug, v_title from public.zemaris
      where (id::text = v_key or slug = v_key) and deleted_at is not null limit 1 for update;
    if not found then raise exception 'Move this Zemari to Trash before permanently deleting it' using errcode = '23514'; end if;
    select count(*) into v_related from public.mezmur_data_import where zemari_id::text = v_slug;
    if v_related > 0 then
      raise exception 'This Zemari is associated with % Mezmurs. Reassign them before permanent deletion.', v_related using errcode = '23503';
    end if;
    delete from public.zemaris where id::text = v_slug and deleted_at is not null;
  elsif p_content_type = 'collection' then
    select collection_slug, title into v_slug, v_title from public.mezmur_collections_import
      where (collection_id = v_key or collection_slug = v_key) and deleted_at is not null limit 1 for update;
    if not found then raise exception 'Move this collection to Trash before permanently deleting it' using errcode = '23514'; end if;
    select count(*) into v_related from public.mezmur_sections_import where collection_slug = v_slug;
    if v_related > 0 then raise exception 'This collection still contains % sections', v_related using errcode = '23503'; end if;
    delete from public.mezmur_collections_import where collection_slug = v_slug and deleted_at is not null;
  elsif p_content_type = 'section' then
    select section_slug, title into v_slug, v_title from public.mezmur_sections_import
      where (section_id = v_key or section_slug = v_key) and deleted_at is not null limit 1 for update;
    if not found then raise exception 'Move this section to Trash before permanently deleting it' using errcode = '23514'; end if;
    delete from public.mezmur_section_links_import where section_slug = v_slug;
    delete from public.mezmur_sections_import where section_slug = v_slug and deleted_at is not null;
  else
    raise exception 'Unsupported Hymns content type: %', p_content_type using errcode = '22023';
  end if;

  insert into public.content_deletion_events(content_type, content_key, content_title, action, actor_id, actor_role,
    details) values (p_content_type, v_key, v_title, 'permanently_deleted', v_actor, v_role,
    jsonb_build_object('removed_relationship_count', v_related));
  return jsonb_build_object('content_type', p_content_type, 'content_key', v_key, 'action', 'permanently_deleted');
end;
$$;

create or replace function public.reassign_and_delete_zemari(p_zemari_id uuid, p_target_zemari_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := auth.uid();
  v_role text;
  v_source public.zemaris%rowtype;
  v_target public.zemaris%rowtype;
  v_count integer;
begin
  select role::text into v_role from public.profiles where id = v_actor;
  if v_actor is null or v_role is distinct from 'super_admin' then
    raise exception 'Only a super admin can reassign and permanently delete a Zemari' using errcode = '42501';
  end if;
  if p_zemari_id = p_target_zemari_id then raise exception 'Choose a different target Zemari' using errcode = '22023'; end if;
  select * into v_source from public.zemaris where id = p_zemari_id and deleted_at is not null for update;
  if not found then raise exception 'Move this Zemari to Trash before permanently deleting it' using errcode = '23514'; end if;
  select * into v_target from public.zemaris where id = p_target_zemari_id and deleted_at is null for update;
  if not found then raise exception 'The replacement Zemari is unavailable or in Trash' using errcode = '23503'; end if;

  update public.mezmur_data_import set zemari_id = v_target.id, singer_id = v_target.id::text,
    singer_slug = v_target.slug, singer_name = v_target.name, updated_at = clock_timestamp()::text
    where zemari_id = v_source.id;
  get diagnostics v_count = row_count;
  delete from public.zemaris where id = v_source.id and deleted_at is not null;
  insert into public.content_deletion_events(content_type, content_key, content_title, action, actor_id, actor_role, details)
    values ('zemari', v_source.id::text, v_source.name, 'reassigned_and_deleted', v_actor, v_role,
      jsonb_build_object('replacement_zemari_id', v_target.id, 'reassigned_mezmur_count', v_count));
  return jsonb_build_object('content_type', 'zemari', 'content_key', v_source.id, 'action', 'reassigned_and_deleted',
    'replacement_zemari_id', v_target.id, 'reassigned_mezmur_count', v_count);
end;
$$;

revoke delete on public.mezmur_data_import, public.zemaris,
  public.mezmur_collections_import, public.mezmur_sections_import from authenticated;
revoke all on function public.trash_hymn_content(text, text) from public, anon;
revoke all on function public.restore_hymn_content(text, text) from public, anon;
revoke all on function public.permanently_delete_hymn_content(text, text) from public, anon;
revoke all on function public.reassign_and_delete_zemari(uuid, uuid) from public, anon;
grant execute on function public.trash_hymn_content(text, text) to authenticated;
grant execute on function public.restore_hymn_content(text, text) to authenticated;
grant execute on function public.permanently_delete_hymn_content(text, text) to authenticated;
grant execute on function public.reassign_and_delete_zemari(uuid, uuid) to authenticated;

create or replace view public.zemaris_with_counts
with (security_invoker = true)
as
select
  z.id,
  z.slug,
  z.name,
  z.name_amharic,
  z.bio,
  z.bio_amharic,
  z.image_path,
  z.image_alt,
  z.youtube_url,
  z.website_url,
  z.sort_order,
  z.is_featured,
  z.status,
  z.created_at,
  z.updated_at,
  (select count(*)::integer from public.mezmur_data_import m
    where m.zemari_id = z.id and m.deleted_at is null
      and lower(trim(coalesce(m.status, ''))) = 'published') as published_mezmur_count,
  (select count(*)::integer from public.mezmur_data_import m
    where m.zemari_id = z.id and m.deleted_at is null) as mezmur_count,
  z.deleted_at,
  z.deleted_by,
  z.deleted_from_status
from public.zemaris z;

grant select on public.zemaris_with_counts to anon, authenticated;
notify pgrst, 'reload schema';
commit;
