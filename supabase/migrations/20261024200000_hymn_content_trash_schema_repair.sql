-- Ordinary content saves must not be able to forge deletion audit metadata.
-- The RPCs below enable this transaction-local guard immediately before their
-- controlled update. Service-role maintenance remains possible.
create or replace function public.guard_hymn_trash_metadata()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if (
    old.deleted_at is distinct from new.deleted_at
    or old.deleted_by is distinct from new.deleted_by
    or old.deleted_from_status is distinct from new.deleted_from_status
  )
  and coalesce(current_setting('app.hymn_trash_rpc', true), '') <> 'on'
  and coalesce(auth.role(), '') <> 'service_role' then
    raise exception 'Trash metadata can only be changed through the Hymns Trash actions'
      using errcode = '42501';
  end if;
  return new;
end;
$$;

