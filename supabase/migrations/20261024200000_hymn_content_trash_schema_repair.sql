create or replace function public.permanently_delete_hymn_content(p_content_type text, p_content_key text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := auth.uid();
  v_role text;
  v_key text := trim(coalesce(p_content_key, ''));
  v_resolved_key text;
  v_slug text;
  v_title text;
  v_row_tid tid;
  v_zemari_id uuid;
  v_related integer := 0;
  v_removed integer := 0;
begin
  select role::text into v_role from public.profiles where id = v_actor;
  if v_actor is null or v_role is distinct from 'super_admin' then
    raise exception 'Only a super admin can permanently delete content' using errcode = '42501';
  end if;
  if v_key = '' then raise exception 'Content key is required' using errcode = '22023'; end if;

  if p_content_type = 'mezmur' then
    select ctid, coalesce(nullif(trim(mezmur_id), ''), slug), slug, title
      into v_row_tid, v_resolved_key, v_slug, v_title
    from public.mezmur_data_import
    where (mezmur_id = v_key or slug = v_key) and deleted_at is not null
    order by case when mezmur_id = v_key then 0 else 1 end, imported_at, import_id
    limit 1 for update;
    if not found then raise exception 'Move this Mezmur to Trash before permanently deleting it' using errcode = '23514'; end if;
    delete from public.mezmur_section_links_import where mezmur_slug = v_slug;
    get diagnostics v_related = row_count; v_removed := v_removed + v_related;
    delete from public.mezmur_category_links_import where mezmur_slug = v_slug;
    get diagnostics v_related = row_count; v_removed := v_removed + v_related;
    delete from public.mezmur_occasion_links_import where mezmur_slug = v_slug;
    get diagnostics v_related = row_count; v_removed := v_removed + v_related;
    delete from public.mezmur_data_import where ctid = v_row_tid and deleted_at is not null;
  elsif p_content_type = 'zemari' then
    select id, id::text, name into v_zemari_id, v_resolved_key, v_title
    from public.zemaris where (id::text = v_key or slug = v_key) and deleted_at is not null
    order by case when id::text = v_key then 0 else 1 end limit 1 for update;
    if not found then raise exception 'Move this Zemari to Trash before permanently deleting it' using errcode = '23514'; end if;
    select count(*) into v_related from public.mezmur_data_import where zemari_id = v_zemari_id;
    if v_related > 0 then
      raise exception 'This Zemari is associated with % Mezmurs. Reassign them before permanent deletion.', v_related using errcode = '23503';
    end if;
    delete from public.zemaris where id = v_zemari_id and deleted_at is not null;
  elsif p_content_type = 'collection' then
    select ctid, coalesce(nullif(trim(collection_id), ''), collection_slug), collection_slug, title
      into v_row_tid, v_resolved_key, v_slug, v_title
    from public.mezmur_collections_import
    where (collection_id = v_key or collection_slug = v_key) and deleted_at is not null
    order by case when collection_id = v_key then 0 else 1 end, imported_at, import_id
    limit 1 for update;
    if not found then raise exception 'Move this collection to Trash before permanently deleting it' using errcode = '23514'; end if;
    select count(*) into v_related from public.mezmur_sections_import where collection_slug = v_slug;
    if v_related > 0 then
      raise exception 'This collection still contains % sections. Move or remove those sections first.', v_related using errcode = '23503';
    end if;
    delete from public.mezmur_collections_import where ctid = v_row_tid and deleted_at is not null;
  elsif p_content_type = 'section' then
    select ctid, coalesce(nullif(trim(section_id), ''), section_slug), section_slug, title
      into v_row_tid, v_resolved_key, v_slug, v_title
    from public.mezmur_sections_import
    where (section_id = v_key or section_slug = v_key) and deleted_at is not null
    order by case when section_id = v_key then 0 else 1 end, imported_at, import_id
    limit 1 for update;
    if not found then raise exception 'Move this section to Trash before permanently deleting it' using errcode = '23514'; end if;
    delete from public.mezmur_section_links_import where section_slug = v_slug;
    get diagnostics v_removed = row_count;
    delete from public.mezmur_sections_import where ctid = v_row_tid and deleted_at is not null;
  else
    raise exception 'Unsupported Hymns content type: %', p_content_type using errcode = '22023';
  end if;

  insert into public.content_deletion_events(content_type, content_key, content_title, action, actor_id, actor_role, details)
  values (p_content_type, v_resolved_key, v_title, 'permanently_deleted', v_actor, v_role,
    jsonb_build_object('removed_relationship_count', v_removed, 'blocking_reference_count', v_related));
  return jsonb_build_object('content_type', p_content_type, 'content_key', v_resolved_key,
    'action', 'permanently_deleted', 'removed_relationship_count', v_removed);
end;
$$;

create or replace function public.reassign_and_delete_zemari(p_zemari_id uuid, p_target_zemari_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := auth.uid();
  v_role text;
  v_source public.zemaris%rowtype;
  v_target public.zemaris%rowtype;
  v_count integer;
begin
  select role::text into v_role from public.profiles where id = v_actor;
  if v_actor is null or v_role is distinct from 'super_admin' then
    raise exception 'Only a super admin can reassign and permanently delete a Zemari' using errcode = '42501';
  end if;
  if p_zemari_id = p_target_zemari_id then raise exception 'Choose a different target Zemari' using errcode = '22023'; end if;
  select * into v_source from public.zemaris where id = p_zemari_id and deleted_at is not null for update;
  if not found then raise exception 'Move this Zemari to Trash before permanently deleting it' using errcode = '23514'; end if;
  select * into v_target from public.zemaris where id = p_target_zemari_id and deleted_at is null for update;
  if not found then raise exception 'The replacement Zemari is unavailable or in Trash' using errcode = '23503'; end if;

  update public.mezmur_data_import
    set zemari_id = v_target.id, singer_id = v_target.id::text,
        singer_slug = v_target.slug, singer_name = v_target.name,
        updated_at = clock_timestamp()::text
    where zemari_id = v_source.id;
  get diagnostics v_count = row_count;
  delete from public.zemaris where id = v_source.id and deleted_at is not null;
  insert into public.content_deletion_events(content_type, content_key, content_title, action, actor_id, actor_role, details)
  values ('zemari', v_source.id::text, v_source.name, 'reassigned_and_deleted', v_actor, v_role,
    jsonb_build_object('replacement_zemari_id', v_target.id, 'reassigned_mezmur_count', v_count));
  return jsonb_build_object('content_type', 'zemari', 'content_key', v_source.id,
    'action', 'reassigned_and_deleted', 'replacement_zemari_id', v_target.id,
    'reassigned_mezmur_count', v_count);
end;
$$;

