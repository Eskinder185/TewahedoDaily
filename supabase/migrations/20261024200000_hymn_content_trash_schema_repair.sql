create or replace function public.trash_hymn_content(p_content_type text, p_content_key text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := auth.uid();
  v_role text;
  v_key text := trim(coalesce(p_content_key, ''));
  v_resolved_key text;
  v_title text;
  v_previous text;
  v_row_tid tid;
  v_zemari_id uuid;
  v_changed integer := 0;
begin
  select role::text into v_role from public.profiles where id = v_actor;
  if v_actor is null or v_role not in ('admin', 'super_admin') then
    raise exception 'An admin or super admin role is required to move content to Trash' using errcode = '42501';
  end if;
  if v_key = '' then raise exception 'Content key is required' using errcode = '22023'; end if;
  perform set_config('app.hymn_trash_rpc', 'on', true);

  if p_content_type = 'mezmur' then
    select ctid, coalesce(nullif(trim(mezmur_id), ''), slug), title, status
      into v_row_tid, v_resolved_key, v_title, v_previous
    from public.mezmur_data_import
    where mezmur_id = v_key or slug = v_key
    order by case when mezmur_id = v_key then 0 else 1 end, imported_at, import_id
    limit 1 for update;
    if not found then raise exception 'Mezmur not found' using errcode = 'P0002'; end if;
    update public.mezmur_data_import
      set deleted_at = now(), deleted_by = v_actor,
          deleted_from_status = coalesce(deleted_from_status, status), status = 'draft',
          updated_at = clock_timestamp()::text
      where ctid = v_row_tid and deleted_at is null;
  elsif p_content_type = 'zemari' then
    select id, id::text, name, status
      into v_zemari_id, v_resolved_key, v_title, v_previous
    from public.zemaris where id::text = v_key or slug = v_key
    order by case when id::text = v_key then 0 else 1 end limit 1 for update;
    if not found then raise exception 'Zemari not found' using errcode = 'P0002'; end if;
    update public.zemaris
      set deleted_at = now(), deleted_by = v_actor,
          deleted_from_status = coalesce(deleted_from_status, status), status = 'archived'
      where id = v_zemari_id and deleted_at is null;
  elsif p_content_type = 'collection' then
    select ctid, coalesce(nullif(trim(collection_id), ''), collection_slug), title, status
      into v_row_tid, v_resolved_key, v_title, v_previous
    from public.mezmur_collections_import
    where collection_id = v_key or collection_slug = v_key
    order by case when collection_id = v_key then 0 else 1 end, imported_at, import_id
    limit 1 for update;
    if not found then raise exception 'Mezmur collection not found' using errcode = 'P0002'; end if;
    update public.mezmur_collections_import
      set deleted_at = now(), deleted_by = v_actor,
          deleted_from_status = coalesce(deleted_from_status, status), status = 'archived'
      where ctid = v_row_tid and deleted_at is null;
  elsif p_content_type = 'section' then
    select ctid, coalesce(nullif(trim(section_id), ''), section_slug), title, status
      into v_row_tid, v_resolved_key, v_title, v_previous
    from public.mezmur_sections_import
    where section_id = v_key or section_slug = v_key
    order by case when section_id = v_key then 0 else 1 end, imported_at, import_id
    limit 1 for update;
    if not found then raise exception 'Mezmur section not found' using errcode = 'P0002'; end if;
    update public.mezmur_sections_import
      set deleted_at = now(), deleted_by = v_actor,
          deleted_from_status = coalesce(deleted_from_status, status), status = 'archived'
      where ctid = v_row_tid and deleted_at is null;
  else
    raise exception 'Unsupported Hymns content type: %', p_content_type using errcode = '22023';
  end if;

  get diagnostics v_changed = row_count;
  if v_changed > 0 then
    insert into public.content_deletion_events(content_type, content_key, content_title, action, actor_id, actor_role, details)
    values (p_content_type, v_resolved_key, v_title, 'trashed', v_actor, v_role,
      jsonb_build_object('previous_status', v_previous));
  end if;
  return jsonb_build_object('content_type', p_content_type, 'content_key', v_resolved_key,
    'action', 'trashed', 'changed', v_changed > 0, 'previous_status', v_previous);
end;
$$;

