-- Keep staff trash listings complete while public callers only see live rows
-- through the underlying Zemari RLS policy.
create or replace view public.zemaris_with_counts
with (security_invoker = true)
as
select
  z.id, z.slug, z.name, z.name_amharic, z.bio, z.bio_amharic,
  z.image_path, z.image_alt, z.youtube_url, z.website_url,
  z.sort_order, z.is_featured, z.status, z.created_at, z.updated_at,
  (select count(*)::integer from public.mezmur_public m where m.zemari_id = z.id) as published_mezmur_count,
  case when coalesce(public.is_staff(), false) then
    (select count(*)::integer from public.mezmur_data_import m where m.zemari_id = z.id and m.deleted_at is null)
  else
    (select count(*)::integer from public.mezmur_public m where m.zemari_id = z.id)
  end as mezmur_count,
  z.deleted_at, z.deleted_by, z.deleted_from_status
from public.zemaris z;

grant select on public.zemaris_with_counts to anon, authenticated;
notify pgrst, 'reload schema';
commit;
