-- Durable, review-first Mezmur enrichment and bounded bulk publication.
-- Analysis never publishes and suggestions never replace existing links.
begin;

create table if not exists public.mezmur_enrichment_jobs (
  id uuid primary key default gen_random_uuid(),
  mode text not null check (mode in ('all','selected','zemari','classification','missing_categories','missing_occasions','retry_failed')),
  status text not null default 'queued' check (status in ('queued','running','cancel_requested','cancelled','completed','failed')),
  requested_import_ids uuid[] not null default '{}',
  total_count integer not null default 0,
  processed_count integer not null default 0,
  succeeded_count integer not null default 0,
  review_count integer not null default 0,
  failed_count integer not null default 0,
  prompt_version text not null default 'mezmur-enrichment-v1',
  model_name text,
  error_message text,
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  started_at timestamptz,
  completed_at timestamptz,
  updated_at timestamptz not null default now()
);

create table if not exists public.mezmur_enrichment_suggestions (
  id uuid primary key default gen_random_uuid(),
  job_id uuid not null references public.mezmur_enrichment_jobs(id) on delete cascade,
  mezmur_import_id uuid not null references public.mezmur_data_import(import_id) on delete cascade,
  source_updated_at text,
  input_lyrics_hash text,
  model_name text,
  prompt_version text not null,
  analyzed_at timestamptz not null default now(),
  zemari_id uuid references public.zemaris(id) on delete set null,
  zemari_match_method text,
  zemari_confidence numeric(5,4),
  primary_category_slug text,
  category_slugs text[] not null default '{}',
  primary_occasion_slug text,
  occasion_slugs text[] not null default '{}',
  section_import_ids uuid[] not null default '{}',
  evidence jsonb not null default '[]',
  explanation text,
  classification_confidence numeric(5,4),
  requires_review boolean not null default true,
  publication_eligible boolean not null default false,
  publication_block_reason text,
  status text not null default 'suggested' check (status in ('suggested','approved','applied','rejected','failed')),
  error_code text,
  error_message text,
  reviewed_by uuid references auth.users(id),
  reviewed_at timestamptz,
  applied_at timestamptz,
  unique(job_id, mezmur_import_id)
);

create table if not exists public.mezmur_enrichment_events (
  id bigint generated by default as identity primary key,
  job_id uuid references public.mezmur_enrichment_jobs(id) on delete set null,
  mezmur_import_id uuid references public.mezmur_data_import(import_id) on delete set null,
  action text not null,
  outcome text not null check (outcome in ('succeeded','skipped','failed')),
  actor_id uuid references auth.users(id) on delete set null,
  details jsonb not null default '{}',
  created_at timestamptz not null default now()
);

create index if not exists mezmur_enrichment_jobs_status_idx on public.mezmur_enrichment_jobs(status, created_at);
create index if not exists mezmur_enrichment_suggestions_job_status_idx on public.mezmur_enrichment_suggestions(job_id, status);
create index if not exists mezmur_enrichment_suggestions_mezmur_idx on public.mezmur_enrichment_suggestions(mezmur_import_id, analyzed_at desc);

alter table public.mezmur_enrichment_jobs enable row level security;
alter table public.mezmur_enrichment_suggestions enable row level security;
alter table public.mezmur_enrichment_events enable row level security;
grant select, insert, update on public.mezmur_enrichment_jobs to authenticated;
grant select, insert, update on public.mezmur_enrichment_suggestions to authenticated;
grant select on public.mezmur_enrichment_events to authenticated;
grant all on public.mezmur_enrichment_jobs, public.mezmur_enrichment_suggestions, public.mezmur_enrichment_events to service_role;
grant usage, select on sequence public.mezmur_enrichment_events_id_seq to service_role;
revoke all on public.mezmur_enrichment_jobs, public.mezmur_enrichment_suggestions, public.mezmur_enrichment_events from anon;

drop policy if exists mezmur_enrichment_jobs_staff on public.mezmur_enrichment_jobs;
create policy mezmur_enrichment_jobs_staff on public.mezmur_enrichment_jobs for all to authenticated
  using (coalesce(public.is_staff(), false)) with check (coalesce(public.is_staff(), false));
drop policy if exists mezmur_enrichment_suggestions_staff on public.mezmur_enrichment_suggestions;
create policy mezmur_enrichment_suggestions_staff on public.mezmur_enrichment_suggestions for all to authenticated
  using (coalesce(public.is_staff(), false)) with check (coalesce(public.is_staff(), false));
drop policy if exists mezmur_enrichment_events_staff_read on public.mezmur_enrichment_events;
create policy mezmur_enrichment_events_staff_read on public.mezmur_enrichment_events for select to authenticated
  using (coalesce(public.is_staff(), false));

create or replace function public.apply_mezmur_enrichment_suggestion(p_suggestion_id uuid)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  v_actor uuid := auth.uid(); v_role text; v_s public.mezmur_enrichment_suggestions%rowtype;
  v_m public.mezmur_data_import%rowtype; v_slug text; v_z public.zemaris%rowtype;
  v_value text; v_section uuid;
begin
  select role into v_role from public.profiles where id = v_actor;
  if v_actor is null or v_role not in ('admin','super_admin') then
    raise exception 'Admin or Super Admin is required to apply enrichment suggestions' using errcode='42501';
  end if;
  select * into strict v_s from public.mezmur_enrichment_suggestions where id=p_suggestion_id for update;
  select * into strict v_m from public.mezmur_data_import where import_id=v_s.mezmur_import_id and deleted_at is null for update;
  if v_s.status not in ('suggested','approved') then raise exception 'Suggestion is not pending review' using errcode='23514'; end if;
  if v_s.source_updated_at is not null and v_m.updated_at is distinct from v_s.source_updated_at then
    raise exception 'Mezmur changed after analysis; reanalyze before applying' using errcode='40001';
  end if;
  v_slug := trim(v_m.slug);
  if v_slug = '' then raise exception 'Mezmur slug is required for taxonomy links' using errcode='23514'; end if;

  if v_s.zemari_id is not null then
    select * into strict v_z from public.zemaris where id=v_s.zemari_id and deleted_at is null;
    if v_m.zemari_id is null or v_m.zemari_id=v_z.id then
      update public.mezmur_data_import set zemari_id=v_z.id, singer_id=v_z.id::text,
        singer_slug=v_z.slug, singer_name=v_z.name, updated_at=clock_timestamp()::text
      where import_id=v_m.import_id;
    else
      raise exception 'A manually linked Zemari differs from the suggestion' using errcode='23514';
    end if;
  end if;

  foreach v_value in array v_s.category_slugs loop
    if not exists (select 1 from public.categories where slug=v_value and coalesce(status,'published') <> 'archived') then
      raise exception 'Unknown or archived category: %', v_value using errcode='23514';
    end if;
    insert into public.mezmur_category_links_import(mezmur_slug,category_slug,source_category,confidence)
      select v_slug,v_value,'ai-suggestion-reviewed','verified'
      where not exists (select 1 from public.mezmur_category_links_import where mezmur_slug=v_slug and category_slug=v_value);
  end loop;
  foreach v_value in array v_s.occasion_slugs loop
    if not exists (select 1 from public.mezmur_occasions where slug=v_value and status <> 'archived') then
      raise exception 'Unknown or archived occasion: %', v_value using errcode='23514';
    end if;
    insert into public.mezmur_occasion_links_import(mezmur_slug,occasion_slug)
      select v_slug,v_value where not exists
      (select 1 from public.mezmur_occasion_links_import where mezmur_slug=v_slug and occasion_slug=v_value);
  end loop;
  foreach v_section in array v_s.section_import_ids loop
    if not exists (select 1 from public.mezmur_sections_import where import_id=v_section and deleted_at is null) then
      raise exception 'Unknown or deleted hymn section: %', v_section using errcode='23514';
    end if;
    insert into public.mezmur_section_links_import(mezmur_slug,section_slug,sort_order,is_primary)
      select v_slug,s.section_slug,'0','false' from public.mezmur_sections_import s
      where s.import_id=v_section and not exists
      (select 1 from public.mezmur_section_links_import l where l.mezmur_slug=v_slug and l.section_slug=s.section_slug);
  end loop;
  update public.mezmur_enrichment_suggestions set status='applied',reviewed_by=v_actor,
    reviewed_at=coalesce(reviewed_at,now()),applied_at=now() where id=v_s.id;
  insert into public.mezmur_enrichment_events(job_id,mezmur_import_id,action,outcome,actor_id,details)
    values(v_s.job_id,v_s.mezmur_import_id,'apply_suggestion','succeeded',v_actor,jsonb_build_object('suggestion_id',v_s.id));
  return jsonb_build_object('suggestion_id',v_s.id,'mezmur_import_id',v_s.mezmur_import_id,'status','applied');
end $$;

create or replace function public.bulk_publish_mezmur_imports(p_import_ids uuid[])
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  v_actor uuid:=auth.uid(); v_role text; v_id uuid; v_m public.mezmur_data_import%rowtype;
  v_published integer:=0; v_skipped integer:=0; v_failed integer:=0; v_results jsonb:='[]'; v_result jsonb;
begin
  select role into v_role from public.profiles where id=v_actor;
  if v_actor is null or v_role <> 'super_admin' then
    raise exception 'Super Admin is required for bulk publication' using errcode='42501';
  end if;
  if cardinality(coalesce(p_import_ids,'{}')) > 100 then raise exception 'Bulk publication is limited to 100 records per batch' using errcode='22023'; end if;
  foreach v_id in array coalesce(p_import_ids,'{}') loop
    begin
      perform pg_advisory_xact_lock(hashtextextended('mezmur-bulk-publish:'||v_id::text,0));
      select * into strict v_m from public.mezmur_data_import where import_id=v_id and deleted_at is null for update;
      if lower(trim(coalesce(v_m.status,'')))='published' then
        v_skipped:=v_skipped+1; v_results:=v_results||jsonb_build_object('import_id',v_id,'outcome','skipped','reason','already published');
      else
        v_result:=public.publish_mezmur_import(v_m.slug,v_m.updated_at);
        v_published:=v_published+1; v_results:=v_results||jsonb_build_object('import_id',v_id,'outcome','published','result',v_result);
        insert into public.mezmur_enrichment_events(mezmur_import_id,action,outcome,actor_id,details)
          values(v_id,'bulk_publish','succeeded',v_actor,v_result);
      end if;
    exception when others then
      v_failed:=v_failed+1; v_results:=v_results||jsonb_build_object('import_id',v_id,'outcome','failed','sqlstate',sqlstate,'reason',sqlerrm);
      insert into public.mezmur_enrichment_events(mezmur_import_id,action,outcome,actor_id,details)
        values(
          case when exists(select 1 from public.mezmur_data_import where import_id=v_id) then v_id else null end,
          'bulk_publish','failed',v_actor,
          jsonb_build_object('requested_import_id',v_id,'sqlstate',sqlstate,'reason',sqlerrm)
        );
    end;
  end loop;
  return jsonb_build_object('published',v_published,'skipped',v_skipped,'failed',v_failed,'results',v_results);
end $$;

revoke all on function public.apply_mezmur_enrichment_suggestion(uuid) from public,anon;
revoke all on function public.bulk_publish_mezmur_imports(uuid[]) from public,anon;
grant execute on function public.apply_mezmur_enrichment_suggestion(uuid) to authenticated;
grant execute on function public.bulk_publish_mezmur_imports(uuid[]) to authenticated;
notify pgrst,'reload schema';
commit;
