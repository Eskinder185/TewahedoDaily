/**
 * Read-only Faith Challenges inventory: bundled counts, publication ledger, generated artifacts and publication blockers.
 * Reads local JSON only. No network, no database, no writes unless --write is passed (writes the Markdown report).
 * Usage: node scripts/play/inventory-report.mjs [--write]
 */
import { readFileSync, existsSync, writeFileSync } from 'node:fs'
const J = path => JSON.parse(readFileSync(path, 'utf8'))
const A = 'artifacts/faith-challenges/'
const counts = J('src/lib/play/generated/counts.json')
const ledger = J('docs/ai/faith-challenges-publication-ledger.json')
const pending = existsSync(A + 'generated-cms-drafts-2026-11-04.json') ? J(A + 'generated-cms-drafts-2026-11-04.json') : []
const dry = existsSync(A + 'generated-import-dry-run-2026-11-04.json') ? J(A + 'generated-import-dry-run-2026-11-04.json') : null
const bundledIds = new Set(ledger.items.map(item => item.id))
const overlap = pending.filter(item => bundledIds.has(item.stable_id)).length
const size = value => Array.isArray(value) ? value.length : value && typeof value === 'object' ? (Object.values(value).find(Array.isArray)?.length ?? 0) : 0
function artifact(phase, file) { const path = `${A}${phase}/${file}`; return existsSync(path) ? size(J(path)) : null }
const ART = {
  trivia: [], emoji: [['emoji', 'questions.json']], 'finish-the-verse': [], history: [['history', 'questions.json']],
  'who-am-i': [['who-am-i', 'cards.json']], match: [['match', 'pairs.json']], 'bible-timeline': [['timeline', 'chains.json']],
  feasts: [['feasts', 'decks.json']], saints: [['saints', 'decks.json']], 'icon-memory': [['icon-memory', 'sets.json']],
  'finish-the-mezmur': [['mezmur', 'sample-questions.json']], adventures: [],
}
const GAMES = ['trivia', 'emoji', 'finish-the-verse', 'history', 'who-am-i', 'match', 'bible-timeline', 'feasts', 'saints', 'icon-memory', 'finish-the-mezmur', 'adventures']
const rows = GAMES.map(game => {
  const c = counts[game], s = ledger.summary[game] || (game === 'bible-timeline' ? ledger.summary['bible-timeline'] : null)
  const art = ART[game].map(([dir, file]) => `p2 ${artifact('phase-2', `${dir}/${file}`) ?? '–'} / p3 ${artifact('phase-3', `${dir}/${file}`) ?? '–'}`).join('; ') || '–'
  return { game, unit: c?.unit ?? (game === 'finish-the-mezmur' ? 'songs (live published Mezmur)' : '–'), bundled: c ? `${c.total} (built-in ${c.builtIn} + approved generated ${c.generated})` : (game === 'finish-the-mezmur' ? 'reads published mezmur_public' : '0'),
    ledger: s ? `published ${s.published}, duplicate ${s.duplicate}, rejected ${s.rejected}, unresolved ${s.unresolved}` : '–', artifacts: art }
})
const md = [`# Faith Challenges content inventory`, '',
  `Generated by \`node scripts/play/inventory-report.mjs --write\`. Local files only; **database counts are not read here** (published database count: unknown until staging/RLS is verified, treat as 0 for public claims).`, '',
  '| Game | Unit | Bundled approved (legacy runtime) | Publication ledger | Generated artifact units (not approved) |', '|---|---|---|---|---|',
  ...rows.map(r => `| ${r.game} | ${r.unit} | ${r.bundled} | ${r.ledger} | ${r.artifacts} |`), '',
  '## Unresolved / blocked (ledger reasons)', '', ...Object.entries(ledger.reasons).map(([reason, n]) => `- ${n} × ${reason}`), '',
  '## Pending CMS import package (trivia + finish-the-verse)', '',
  `- Package: ${pending.length} draft rows (dry-run: ${dry ? `${dry.valid} valid, ${dry.rejected} rejected, databaseReconciled=${dry.databaseReconciled}` : 'missing'}).`,
  `- Rows whose ID is already in the published ledger/bundled bank: **${overlap}** of ${pending.length}.`,
  '- Every row stays a draft: editorial approval and verifiedLocales must be set by a human reviewer in the CMS. Nothing here is approved or published.', '',
  '## Publication blockers by game', '',
  '- trivia / finish-the-verse / emoji: bundled bank is approved and live; further generated rows need reviewer approval, then the CMS review RPC.',
  '- who-am-i / match / bible-timeline: bundled approved items live; unresolved items need source/doctrinal verification (see reasons).',
  '- history: only the 6 built-in questions are live; 120 generated items await doctrinal/source review.',
  '- feasts / saints / icon-memory: bundled image banks only; generated decks/sets reuse the same approved image catalog and need editorial sign-off; no server reader beyond database-only mode.',
  '- finish-the-mezmur: reads published Mezmur lyrics directly (needs ≥4 songs with ≥5 usable lines); source-only rows in database-only mode.',
  '- adventures: 6 built-in stories; no generated stories are approved.', '',
  '## Publication plan (not executed)', '',
  '1. Reviewer approves a specific batch in the Studio (sets verifiedLocales honestly).',
  '2. Run the offline dry-run; confirm 0 rejected and 0 ID collisions with the ledger.',
  '3. Import as drafts through the authorized CMS path; then move review → approved → published through `review_play_content` (reversible: published → draft / archived).',
  '4. Rollback: transition the batch back to draft/archived via the same RPC; no deletes.', ''].join('\n')
console.log(md)
if (process.argv.includes('--write')) writeFileSync('docs/ai/FAITH-CHALLENGES-INVENTORY-2026-11-14.md', md)
